#!/usr/bin/env python3
"""Aggregate data/episodes/v044_v046_forensic.csv (from
scripts/forensic_v044_v046_full.py) into W-vs-L comparison tables.

Anti "forensic loss-analysis trap" discipline (david valor, forum topic 713608,
see PLAN.md §L): every candidate signal below is reported as a distribution
split by result (win vs loss), not as a description of losses alone. A signal
that looks identical in W and L games is noise dressed as a finding, not a
lever for v048.

Output: data/episodes/v044_v046_forensic_summary.md
"""
import csv
import math
import statistics
from collections import defaultdict
from pathlib import Path

IN_CSV = Path("data/episodes/v044_v046_forensic.csv")
OUT_MD = Path("data/episodes/v044_v046_forensic_summary.md")


def wilson_ci(wins: float, n: float, z: float = 1.96) -> tuple[float, float]:
    if n <= 0:
        return (0.0, 1.0)
    p = wins / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    margin = (z * math.sqrt(max(p * (1 - p), 0.0) / n + z * z / (4 * n * n))) / denom
    return (max(0.0, centre - margin), min(1.0, centre + margin))


def load_rows() -> list[dict]:
    with open(IN_CSV, newline="") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for k, v in list(r.items()):
            if v == "":
                r[k] = None
            elif v is not None and k not in ("episode_id", "submission", "opponent_team", "archetype_truth", "result", "result_reason"):
                try:
                    r[k] = float(v) if "." in v or v in ("None",) else int(v)
                except (ValueError, TypeError):
                    pass
    return rows


def wr_table(rows: list[dict], group_keys: tuple[str, ...]) -> list[str]:
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for r in rows:
        key = tuple(r[k] for k in group_keys)
        groups[key].append(r)
    lines = [f"| {' | '.join(group_keys)} | N | W | L | WR | Wilson95 |", "|" + "---|" * (len(group_keys) + 4)]
    for key in sorted(groups, key=lambda k: (-len(groups[k]), k)):
        grp = groups[key]
        n = len(grp)
        w = sum(1 for r in grp if r["result"] == "win")
        l = sum(1 for r in grp if r["result"] == "loss")
        wr = w / n if n else 0.0
        lo, hi = wilson_ci(w, n)
        key_str = " | ".join(str(k) for k in key)
        lines.append(f"| {key_str} | {n} | {w} | {l} | {wr:.1%} | [{lo:.1%}, {hi:.1%}] |")
    return lines


def numeric_wl_split(rows: list[dict], field: str) -> list[str]:
    lines = [f"### `{field}` — win vs loss distribution", "", "| submission | result | N | mean | median |", "|---|---|---|---|---|"]
    for sub in sorted({r["submission"] for r in rows}):
        for result in ("win", "loss"):
            vals = [r[field] for r in rows if r["submission"] == sub and r["result"] == result and r[field] is not None]
            if not vals:
                lines.append(f"| {sub} | {result} | 0 | - | - |")
                continue
            lines.append(f"| {sub} | {result} | {len(vals)} | {statistics.mean(vals):.3f} | {statistics.median(vals):.3f} |")
    return lines


def supporter_timing_wl(rows: list[dict], field: str, label: str) -> list[str]:
    lines = [f"### {label} — played vs not played, by result", "", "| submission | result | played_N | played_frac | median_turn |", "|---|---|---|---|---|"]
    for sub in sorted({r["submission"] for r in rows}):
        for result in ("win", "loss"):
            grp = [r for r in rows if r["submission"] == sub and r["result"] == result]
            if not grp:
                continue
            played = [r[field] for r in grp if r[field] is not None]
            frac = len(played) / len(grp)
            med = statistics.median(played) if played else float("nan")
            lines.append(f"| {sub} | {result} | {len(played)}/{len(grp)} | {frac:.1%} | {med if played else '-'} |")
    return lines


def prize_lead_sign_wl(rows: list[dict], field: str) -> list[str]:
    lines = [f"### `{field}` sign (ahead/tied/behind on knockouts) — by result", "", "| submission | result | ahead | tied | behind | N |", "|---|---|---|---|---|---|"]
    for sub in sorted({r["submission"] for r in rows}):
        for result in ("win", "loss"):
            grp = [r[field] for r in rows if r["submission"] == sub and r["result"] == result and r[field] is not None]
            if not grp:
                continue
            ahead = sum(1 for v in grp if v > 0)
            tied = sum(1 for v in grp if v == 0)
            behind = sum(1 for v in grp if v < 0)
            lines.append(f"| {sub} | {result} | {ahead} | {tied} | {behind} | {len(grp)} |")
    return lines


def main():
    rows = load_rows()
    md = ["# v044_resub / v046_judgefix forensic summary — all 129 live tracked-2 games", "",
          "Generated by `scripts/analyze_v044_v046_forensic.py` from `scripts/forensic_v044_v046_full.py`'s "
          "output. Every table below splits win vs loss explicitly — a signal that looks the same in both "
          "columns is not a lever for v048 (see PLAN.md §L, david valor forensic-loss-trap discipline).",
          "", "## WR by submission × archetype (ground-truth deck, Wilson95 CI)", ""]
    md += wr_table(rows, ("submission", "archetype_truth"))

    md += ["", "## result_reason distribution by submission × result", ""]
    md += wr_table(rows, ("submission", "result_reason"))

    md += ["", "## Candidate signal: bench thinness (fraction of our own MAIN decisions with bench<=1)", ""]
    md += numeric_wl_split(rows, "bench_thin_frac")

    md += ["", "## Candidate signal: archetype detect-lag (turn our board-only matchup guess first matches ground truth)", ""]
    md += numeric_wl_split(rows, "detect_lag_turn")
    md += ["", "## Candidate signal: detect_match_frac (fraction of decisions with correct board-only matchup guess)", ""]
    md += numeric_wl_split(rows, "detect_match_frac")

    md += ["", "## Candidate signal: prize lead trajectory (my_KOs - opp_KOs), sign only, by turn milestone", ""]
    for field in ("prize_lead_turn4", "prize_lead_turn8", "prize_lead_turn12", "prize_lead_turn16", "prize_lead_final"):
        md += prize_lead_sign_wl(rows, field)
        md.append("")

    md += ["", "## Candidate signal: supporter timing (Judge / Boss's Orders / Xerosic's Machinations)", ""]
    for cid, label in (("judge_played_us", "JUDGE played by us"), ("judge_played_opp", "JUDGE played by opponent"),
                        ("boss_played_us", "BOSS's Orders played by us"), ("boss_played_opp", "BOSS's Orders played by opponent"),
                        ("xerosic_played_us", "Xerosic's Machinations played by us"), ("xerosic_played_opp", "Xerosic's Machinations played by opponent")):
        md += supporter_timing_wl(rows, cid, label)
        md.append("")

    OUT_MD.write_text("\n".join(md) + "\n")
    print(f"Wrote {OUT_MD} ({len(rows)} rows analyzed)")


if __name__ == "__main__":
    main()
